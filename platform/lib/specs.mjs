/**
 * Engine specifications (Oct 19, 2026).
 *
 * Every engine publishes a compact spec: the decision it supports, its inputs and
 * output, setup and environments, whether it acts or only analyzes, where the
 * user's information goes, and its limitations and review requirement.
 *
 * Sources, so nothing is typed twice:
 *   - skills/<slug>/spec.json   hand-written: decision, limitations, review,
 *                               optional agent_writes (a file the SKILL tells the
 *                               agent to write; the engine itself never writes)
 *   - SKILL.md frontmatter      inputs, outputs, version, phase, agents
 *   - the engine source         scanned for network, file-write and process calls
 *   - platform/engine-environments.json   which agents have been tested
 *
 * Generated by platform/scripts/generate-engine-specs.mjs into docs/engines/.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { frontmatter, readText } from "./catalog.mjs";

export const HOSTED_MCP = "https://aaj-engines-mcp.sarojkjha10.workers.dev/mcp";
export const REPO = "sarojkjha/aaj-marketing-skills";

export const DATA_FLOW = [
  {
    path: "Skill installed in your agent, or the local MCP server",
    where: "The engine runs on your machine and AAJ receives nothing. Your AI agent still sends what you give it to its model provider (Anthropic, OpenAI and so on), under your own account's terms.",
  },
  {
    path: "Hosted MCP server",
    where: "Your agent's model provider, as above, plus AAJ's server on Cloudflare, which receives the engine inputs over HTTPS, runs them in memory and keeps no copy. Cloudflare keeps error logs (no inputs) for up to 7 days.",
  },
];

const LIMITS = { decision: 160, limitation: 240, review: 320 };

/** Source with comments and string contents removed, for the capability scan. */
function codeOnly(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:\\])\/\/.*$/gm, "$1")
    .replace(/`(?:\\[\s\S]|[^`\\])*`/g, "``");
}

/**
 * What an engine can do beyond computing. All four are false for every engine
 * today; the check fails if one becomes true, so the "analyzes only" line can't
 * go stale.
 */
export function scanEngine(file) {
  const src = codeOnly(readText(file));
  // Calls are matched with string contents blanked, so an engine that prints the
  // word "fetch(" isn't flagged; module names are matched on the code with strings.
  const calls = src.replace(/'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"/g, '""');
  const reads = [...src.matchAll(/readFileSync\(([^)]*)\)/g)].map((m) => m[1]);
  return {
    network: /\bfetch\s*\(|XMLHttpRequest|WebSocket/.test(calls) || /require\(\s*['"](?:node:)?(?:https?|net|tls|dgram|dns|http2)['"]\s*\)/.test(src),
    writesFiles: /\b(?:writeFileSync|writeFile|appendFileSync|appendFile|createWriteStream|mkdirSync|rmSync|unlinkSync|renameSync|copyFileSync)\s*\(/.test(calls),
    spawns: /require\(\s*['"](?:node:)?child_process['"]\s*\)/.test(src) || /\b(?:execSync|spawnSync|execFile)\s*\(/.test(calls),
    readsInputFile: reads.some((a) => !/__filename/.test(a)),
  };
}

export function loadSpecSource(skill) {
  const p = join(skill.dir, "spec.json");
  if (!existsSync(p)) return null;
  return JSON.parse(readFileSync(p, "utf8"));
}

/** Problems with one spec.json, as readable strings. Empty means complete. */
export function validateSpecSource(slug, src) {
  if (!src) return [`${slug}: skills/${slug}/spec.json is missing`];
  const errs = [];
  const str = (v) => typeof v === "string" && v.trim().length > 0;
  if (!str(src.decision)) errs.push(`${slug}: "decision" is missing`);
  else {
    if (!src.decision.trim().endsWith("?")) errs.push(`${slug}: "decision" should be the question it answers, ending in "?"`);
    if (src.decision.length > LIMITS.decision) errs.push(`${slug}: "decision" is over ${LIMITS.decision} characters`);
  }
  if (!Array.isArray(src.limitations) || src.limitations.length < 2 || src.limitations.length > 4) {
    errs.push(`${slug}: "limitations" needs 2 to 4 items`);
  } else {
    src.limitations.forEach((l, i) => {
      if (!str(l)) errs.push(`${slug}: limitation ${i + 1} is empty`);
      else if (l.length > LIMITS.limitation) errs.push(`${slug}: limitation ${i + 1} is over ${LIMITS.limitation} characters`);
    });
  }
  if (!str(src.review)) errs.push(`${slug}: "review" is missing`);
  else if (src.review.length > LIMITS.review) errs.push(`${slug}: "review" is over ${LIMITS.review} characters`);
  if ("agent_writes" in src && !str(src.agent_writes)) errs.push(`${slug}: "agent_writes" is empty; remove it or name the file`);
  const known = new Set(["decision", "limitations", "review", "agent_writes"]);
  for (const k of Object.keys(src)) if (!known.has(k)) errs.push(`${slug}: unknown field "${k}"`);
  return errs;
}

export function loadEnvironments(root) {
  const p = join(root, "platform", "engine-environments.json");
  return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : { tested: [] };
}

/** The full spec for one engine, as published in docs/engines/specs.json. */
export function buildSpec(skill, engineFile, id, env) {
  const { data } = frontmatter(readText(skill.skillMd));
  const src = loadSpecSource(skill) || {};
  const scan = scanEngine(engineFile);
  const listed = Array.isArray(data.agents) ? data.agents : [];
  const tested = (env.tested || []).filter(Boolean);
  return {
    id,
    slug: skill.slug,
    title: skill.title,
    version: data.version || "",
    phase: skill.phase,
    category: skill.category,
    decision: src.decision || "",
    inputs: data.inputs || "",
    outputs: data.outputs || "",
    engine: `skills/${skill.slug}/resources/${engineFile.split("/").pop()}`,
    setup: {
      install: `npx skills add ${REPO} --skill ${skill.slug}`,
      hosted_mcp: HOSTED_MCP,
      local_mcp: "node platform/mcp/server.mjs (Node 18 or newer)",
      runtime: "Node 18 or newer for local runs; none for the hosted server",
      agents_listed: listed,
      agents_tested: tested,
    },
    acts: {
      analyzes_only: !scan.network && !scan.writesFiles && !scan.spawns,
      network_calls: scan.network,
      writes_files: scan.writesFiles,
      starts_processes: scan.spawns,
      reads_a_file_you_name: scan.readsInputFile,
      agent_writes: src.agent_writes || null,
    },
    data_flow: DATA_FLOW,
    limitations: src.limitations || [],
    review: src.review || "",
  };
}

/** One-paragraph version for the MCP describe_engine tool. */
export function specForAgent(spec) {
  if (!spec || !spec.decision) return "";
  const lines = [
    `Decision it supports: ${spec.decision}`,
    `Acts? ${spec.acts.analyzes_only ? "Analyzes only: no network calls, writes no files, changes nothing in the user's tools." : "See the spec."}`,
    "Limitations:",
    ...spec.limitations.map((l) => `- ${l}`),
    `Review before acting: ${spec.review}`,
    "Tell the user these limitations when you present the result.",
  ];
  return lines.join("\n");
}

export function renderSpecMarkdown(spec) {
  const a = spec.acts;
  const acts = a.analyzes_only
    ? "Analyzes only. The engine makes no network calls, writes no files and changes nothing in your tools; it returns text and JSON."
    : `Network calls: ${a.network_calls ? "yes" : "no"}. Writes files: ${a.writes_files ? "yes" : "no"}. Starts processes: ${a.starts_processes ? "yes" : "no"}.`;
  const reads = a.reads_a_file_you_name ? " It can read an input file you name on the command line; it reads nothing else." : "";
  const agentWrites = a.agent_writes ? ` The skill asks your agent to write ${a.agent_writes} in your project (the engine itself writes nothing).` : "";
  const tested = spec.setup.agents_tested.length ? spec.setup.agents_tested.join(", ") : "not recorded yet";
  const listed = spec.setup.agents_listed.length ? spec.setup.agents_listed.join(", ") : "any agent that reads Agent Skills";
  return `# ${spec.title}

\`${spec.id}\` · v${spec.version || "—"} · ${spec.phase || "—"} · ${spec.category || "—"}
<!-- Generated by platform/scripts/generate-engine-specs.mjs from skills/${spec.slug}/spec.json and SKILL.md. Do not edit. -->

**Decision it supports:** ${spec.decision}

**Inputs:** ${spec.inputs}

**Output:** ${spec.outputs}

**Setup:**
- Install the skill: \`${spec.setup.install}\`
- Or connect the hosted MCP server, no install: \`${spec.setup.hosted_mcp}\`
- Or run the local MCP server: ${spec.setup.local_mcp}
- Full input schema: \`node ${spec.engine} --help\`. Worked example: \`node ${spec.engine}\` with no input.
- Agents listed: ${listed}. Tested and recorded: ${tested}.

**Acts or analyzes:** ${acts}${reads}${agentWrites}

**Where your information goes:**

| How you run it | Where your inputs go |
|---|---|
${spec.data_flow.map((d) => `| ${d.path} | ${d.where} |`).join("\n")}

No engine needs customer names, emails or other personal data; leave them out.

**Limitations:**
${spec.limitations.map((l) => `- ${l}`).join("\n")}

**Review before acting:** ${spec.review}

Method: [skills.aajconsult.com/skills/${spec.slug}](https://skills.aajconsult.com/skills/${spec.slug})
`;
}
